// 任务地名特化规则
function translateMission(line) {
  const m = line.match(/^(裏・)?第(\d+)任務 (.+?)([ＥＪＣＤ])(をクリアする)$/);
  if (!m) return null;
  const [_, li, num, placeRaw, rank, __] = m;
  const place = placeMap[placeRaw] || placeRaw;
  const rankMap = { 'Ｅ': 'E', 'Ｊ': 'J', 'Ｃ': 'C', 'Ｄ': 'D' };
  return `${li ? '里·' : ''}通关第${num}任务 ${place}(${rankMap[rank]})`;
}

const out = [];
let translated = 0, skipped = 0;
for (const line of lines) {
  if (existing.has(line)) continue;
  let t = null;
  const half = toHalf(line);
  // 先试任务模式
  t = translateMission(half);
  // 再试模式表
  if (!t) {
    for (const [re2, fmt] of patternMap) {
      const mm = half.match(re2);
      if (mm) {
        t = fmt.replace(/\$(\d+)/g, (_, i) => mm[i] || '');
        break;
      }
    }
  }
  if (t) { out.push([line, t]); translated++; }
  else skipped++;
}
