// 生成 UiDictEquip.cs：装备名 + 附魔效果翻译（来自 kurusuta.xlsx 社区表）
import fs from 'node:fs';

const eq = JSON.parse(fs.readFileSync('E:/dsh/TSKHook/tools/equip-names.json', 'utf8'));
const enc = JSON.parse(fs.readFileSync('E:/dsh/TSKHook/tools/enchant-clean.json', 'utf8'));

// 补翻占位符
eq['ネフィルガロス'] = '奈菲尔加洛斯';
eq['ヴァイキング・スレッジ'] = '维京大锤';
eq['パイルバンカー·ロア'] = '打桩机·罗亚';
// 修正误配(モード花織 被错配为 斩击)
delete eq['モード花織'];

// 附魔表直接使用干净对照(enchant-clean.json: 效果原文->翻译)
const enchant = enc;

const lines = [];
lines.push('// Auto-generated by tools/gen-ui-equip.mjs from kurusuta.xlsx community tables.');
lines.push('// Equipment names + enchant effect translations (simplified Chinese).');
lines.push('using System.Collections.Generic;');
lines.push('');
lines.push('namespace TSKHook;');
lines.push('');
lines.push('public static class UiDictEquip');
lines.push('{');
lines.push('    public static readonly Dictionary<string, string> Entries = new()');
lines.push('    {');
for (const [k, v] of Object.entries({ ...eq, ...enchant }).sort((a, b) => a[0].localeCompare(b[0]))) {
  lines.push(`        { ${JSON.stringify(k)}, ${JSON.stringify(v)} },`);
}
lines.push('    };');
lines.push('}');
lines.push('');
fs.writeFileSync('E:/dsh/TSKHook/UiDictEquip.cs', lines.join('\n'), 'utf8');
console.log(`Wrote UiDictEquip.cs: ${Object.keys(eq).length} equip + ${Object.keys(enchant).length} enchant = ${Object.keys(eq).length + Object.keys(enchant).length} entries`);
console.log('\n=== 附魔样例 ===');
Object.entries(enchant).slice(0, 10).forEach(([k, v]) => console.log(`  ${k} -> ${v}`));
