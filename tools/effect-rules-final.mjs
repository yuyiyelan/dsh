const tests = [
  '自身のEX消費量5％減少',
  '敵単体に144％のダメージ/重さ9.9％ダウン（27CT）/6ノックバック/前から2番目にいる味方のノーツを3前方に移動',
  '対象とその左右２レーンにいる敵すべてに100％のダメージ/被ダメージ17.6％増加（30CT）/17％の確率で萎縮を付与（30CT）',
  '味方全体の基礎ATK20％アップ/魔族の味方の基礎ATK5％アップ',
  '自身の初期シスターゲージ+20%',
  'いずれかの味方がACTバー到達時（ランブル時は除く）に発動',
];
let allOk = true;
for (const t of tests) {
  const r = translateEffect(t);
  const hasJp = /[ァ-ヶ]/.test(r);
  if (hasJp) allOk = false;
  console.log(`  ${t.slice(0, 55)}`);
  console.log(`    -> ${r.slice(0, 70)}${hasJp ? ' ⚠️含日文' : ' ✅'}`);
}
console.log(`\n全部翻译: ${allOk ? '✅' : '❌'}`);

// 输出所有 NoHit 技能效果翻译
const log = 'C:/Users/KK/Twinkle_StarKnightsX/BepInEx/LogOutput.log';
const nohit = fs.readFileSync(log, 'utf8').split(/\r?\n/)
  .filter((l) => l.includes('[NoHit]'))
  .map((l) => l.replace(/^.*\[NoHit\]\s*/, '').trim())
  .filter((l) => /ダメージ|％|CT|ノックバック|ノーツ|萎縮|増加|減少/.test(l));
const entries = [];
const seen = new Set();
for (const l of nohit) {
  if (seen.has(l)) continue;
  seen.add(l);
  entries.push([l, translateEffect(l)]);
}
fs.writeFileSync('E:/dsh/TSKHook/tools/effect-entries.json', JSON.stringify(entries, null, 1), 'utf8');
console.log(`\n技能效果条目: ${entries.length} 条 -> effect-entries.json`);
