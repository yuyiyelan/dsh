// 技能效果规则引擎最终版：全角转半角 + 段级翻译 + 输出词典条目
import fs from 'node:fs';

const toHalf = (s) => s.replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xFEE0)).replace(/％/g, '%');

// 段级翻译规则(顺序重要: 长规则在前)
const segRules = [
  // 伤害
  [/^敵単体に(\d+(?:\.\d+)?)%のダメージ/, '对敌方单体造成$1%伤害'],
  [/^敵全体に(\d+(?:\.\d+)?)%のダメージ/, '对敌方全体造成$1%伤害'],
  [/^対象とその左右(\d+)レーンにいる敵すべてに(\d+(?:\.\d+)?)%のダメージ/, '对目标及左右$1条车道上的所有敌人造成$2%伤害'],
  [/^味方全体の基礎ATK(\d+(?:\.\d+)?)%アップ/, '我方全体基础ATK提升$1%'],
  [/^自身のEX消費量(\d+(?:\.\d+)?)%減少/, '自身EX消耗量减少$1%'],
  [/^自身の初期シスターゲージ\+(\d+)%/, '自身初始修女槽+$1%'],
  [/^自身の初期固有ゲージ\+(\d+)/, '自身初始固有槽+$1'],
  [/被ダメージ(\d+(?:\.\d+)?)%増加/, '受击伤害增加$1%'],
  [/被ダメージ(\d+(?:\.\d+)?)%減少/, '受击伤害减少$1%'],
  [/ダメージ(\d+(?:\.\d+)?)%アップ/, '伤害提升$1%'],
  [/ダメージ(\d+(?:\.\d+)?)%ダウン/, '伤害降低$1%'],
  [/重さ(\d+(?:\.\d+)?)%ダウン/, '重量降低$1%'],
  [/ATK(\d+(?:\.\d+)?)%アップ/, 'ATK提升$1%'],
  [/EX消費量(\d+(?:\.\d+)?)%減少/, 'EX消耗量减少$1%'],
  [/基礎ATK(\d+(?:\.\d+)?)%アップ/, '基础ATK提升$1%'],
  [/上昇値が(\d+(?:\.\d+)?)%アップ/, '提升值增加$1%'],
  // 状态/效果
  [/^(\d+)ノックバック/, '$1格击退'],
  [/^(\d+)%の確率で萎縮を付与（(\d+)CT）/, '$1%概率赋予萎缩（$2CT）'],
  [/萎縮を付与（(\d+)CT）/, '赋予萎缩（$1CT）'],
  [/^(\d+)%の確率で/, '$1%概率'],
  [/前から(\d+)番目にいる味方のノーツを(\d+)前方に移動/, '将从前数第$1位我方成员的音符向前移动$2格'],
  [/味方のノーツを(\d+)前方に移動/, '将我方成员的音符向前移动$1格'],
  [/(\d+)CT/, '$1CT'],
  [/効果時間\+(\d+)CT/, '效果时间+$1CT'],
  [/初期固有ゲージ\+(\d+)/, '初始固有槽+$1'],
  [/初期シスターゲージ\+(\d+)%/, '初始修女槽+$1%'],
  // 属性/种族限定
  [/^(魔族|神族|人族|光属性|闇属性|暗属性|火属性|水属性|雷属性|風属性)の味方の基礎ATK(\d+(?:\.\d+)?)%アップ/, '$1我方基础ATK提升$2%'],
  [/^(魔族|神族|人族|光属性|闇属性|暗属性|火属性|水属性|雷属性|風属性)の味方のATK(\d+(?:\.\d+)?)%アップ/, '$1我方ATK提升$2%'],
  [/^いずれかの味方がACTバー到達時（ランブル時は除く）に発動/, '任意我方成员到达ACT条时（乱斗时除外）发动'],
  [/^いずれかの味方がEXスキル1、または、EXスキル1\+使用時に発動/, '任意我方成员使用EX技能1或EX技能1+时发动'],
  [/^いずれかの味方がランブル勝利後に発動/, '任意我方成员在乱斗胜利后发动'],
  [/^味方全体の基礎ATK(\d+(?:\.\d+)?)%アップ/, '我方全体基础ATK提升$1%'],
  [/^味方全体のATK(\d+(?:\.\d+)?)%アップ/, '我方全体ATK提升$1%'],
  [/^行動CT(\d+(?:\.\d+)?)%短縮/, '行动CT缩短$1%'],
  [/^(魔族|神族|人族)の味方/, '$1我方'],
  [/^(光|闇|暗|火|水|雷|風)属性の味方/, '$1属性我方'],
  [/^味方全体/, '我方全体'],
  [/^味方の/, '我方的'],
];

function translateEffect(text) {
  let s = toHalf(text).trim();
  const segs = s.split('/');
  const out = segs.map((seg) => {
    let r = seg.trim();
    for (const [re, fmt] of segRules) {
      r = r.replace(re, fmt);
    }
    return r;
  });
  return out.join('/');
}

