// Generate UnifiedNames.cs from unified_names_v3.json (v3 merge rules)
import fs from 'node:fs';

const DIR = 'E:/dsh/TSKHook/tools/xlsx-extract';
const data = JSON.parse(fs.readFileSync(`${DIR}/unified_names_v3.json`, 'utf8'));
const { names } = data;

function cs(s) {
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '');
}

let out = `// Auto-generated by tools/gen-unified-names.mjs
// Unified character & NPC name overrides (Japanese original -> Simplified Chinese).
// Sources (priority):
//   - kurusuta.xlsx "星骑士测评" sheet (community-reviewed CN names; limited-edition
//     names only applied to suffixed keys so base characters stay clean)
//   - bilibili wiki (plain base pages preferred; bracket variants extracted)
//   - translation.lolida.best tsk_name/tsk_subname zh_Hant converted to Simplified (fallback)
// Suffixed keys (e.g. フィオナ（魔王覚醒）) reuse the unified base name prefix.
using System.Collections.Generic;

namespace TSKHook;

public static class UnifiedNames
{
    public static readonly Dictionary<string, string> Overrides = new()
    {
`;
for (const [jp, cn] of Object.entries(names)) {
  out += `        { "${cs(jp)}", "${cs(cn)}" },\n`;
}
out += `    };
}
`;

fs.writeFileSync('E:/dsh/TSKHook/UnifiedNames.cs', out, 'utf8');
console.log('written UnifiedNames.cs, entries:', Object.keys(names).length, 'size:', out.length);
